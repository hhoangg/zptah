// Builds the landing page into static files. No dependencies: plain Node.
//
//   node landing/build.mjs [--target prod|beta] [--out DIR]
//
// Output under DIR (default landing/dist):
//   landing/index.html        the page (served at /landing/ and, by the Worker, at / and /home; web/worker/src/landing.ts)
//   landing/landing.css       src/styles/*.css, concatenated in file name order
//   landing/privacy/index.html  the privacy policy of the Mono Browser (Ardia) (served at /privacy by web/worker/src/landing.ts)
//   landing/js/*.js           src/js/*.js as native ES modules plus the blocking boot.js (no bundler)
//   landing/app-icon.png, landing/og.png
// `--target prod` also writes robots.txt and sitemap.xml at the root of DIR (the app's assets directory). `site` (the
// RP_ORIGIN of the app build, https://zptah.app officially) is the host used for canonical, og:url, og:image, sitemap and robots.
// `--target beta` also writes what a site root needs, because the beta host serves only these files: index.html at /,
// robots.txt (disallow all), _headers (the production CSP, X-Robots-Tag: noindex) and the favicons of the web app.
// `--target beta` also changes the Sign in, Get started and Open web app links to absolute https://zptah.app URLs and
// adds a noindex robots meta. Everything else is the same source.
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, 'src');

export const FAVICONS = ['favicon.ico', 'favicon.svg', 'favicon-16x16.png', 'favicon-32x32.png', 'apple-touch-icon.png'];

/** The `_headers` file of the beta host: the CSP of the real host, so beta proves the production behavior. */
export async function betaHeaders() {
  const { buildCsp, COMPANION_HEADERS } = await import(pathToFileUrl(path.join(here, '..', 'worker', 'src', 'csp.ts')));
  const companion = Object.entries(COMPANION_HEADERS).map(([k, v]) => `  ${k}: ${v}`);
  return [
    '# Generated by web/landing/build.mjs (--target beta). Never edit by hand.',
    '/*',
    `  Content-Security-Policy: ${buildCsp('beta.zptah.app')}`,
    ...companion,
    '  X-Robots-Tag: noindex, nofollow',
    '  Cache-Control: no-cache',
    '',
  ].join('\n');
}

function pathToFileUrl(p) {
  return new URL(`file://${p}`).href;
}

export const BETA_ROBOTS = 'User-agent: *\nDisallow: /\n';

export async function build({ target = 'prod', out, site = 'https://zptah.app' }) {
  if (target !== 'prod' && target !== 'beta') throw new Error(`unknown target ${target}`);
  const { renderPage } = await import('./src/html/page.mjs');
  const { renderPrivacy } = await import('./src/html/privacy.mjs');
  const landing = path.join(out, 'landing');
  rmSync(landing, { recursive: true, force: true });
  mkdirSync(path.join(landing, 'js'), { recursive: true });

  const page = renderPage(target, site);
  writeFileSync(path.join(landing, 'index.html'), page);
  const privacy = renderPrivacy(target, site);
  mkdirSync(path.join(landing, 'privacy'), { recursive: true });
  writeFileSync(path.join(landing, 'privacy', 'index.html'), privacy);

  const css = readdirSync(path.join(src, 'styles'))
    .filter((f) => f.endsWith('.css'))
    .sort()
    .map((f) => readFileSync(path.join(src, 'styles', f), 'utf8').trimEnd())
    .join('\n');
  writeFileSync(path.join(landing, 'landing.css'), css + '\n');

  for (const f of readdirSync(path.join(src, 'js')).filter((f) => f.endsWith('.js'))) {
    copyFileSync(path.join(src, 'js', f), path.join(landing, 'js', f));
  }
  copyFileSync(path.join(src, 'assets', 'app-icon.png'), path.join(landing, 'app-icon.png'));
  if (existsSync(path.join(src, 'assets', 'og.png'))) copyFileSync(path.join(src, 'assets', 'og.png'), path.join(landing, 'og.png'));
  else console.warn('landing: src/assets/og.png is missing, og:image will 404');

  if (target === 'prod') {
    // Served from the site root next to the app's own files (the Worker's assets directory).
    writeFileSync(path.join(out, 'robots.txt'), readFileSync(path.join(src, 'robots.txt'), 'utf8').replaceAll('__SITE__', site));
    writeFileSync(path.join(out, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url>\n    <loc>${site}/</loc>\n  </url>\n  <url>\n    <loc>${site}/privacy</loc>\n  </url>\n</urlset>\n`);
  }
  if (target === 'beta') {
    writeFileSync(path.join(out, 'index.html'), page);
    mkdirSync(path.join(out, 'privacy'), { recursive: true });
    writeFileSync(path.join(out, 'privacy', 'index.html'), privacy);
    writeFileSync(path.join(out, 'robots.txt'), BETA_ROBOTS);
    writeFileSync(path.join(out, '_headers'), await betaHeaders());
    for (const f of FAVICONS) copyFileSync(path.join(here, '..', 'app', 'public', f), path.join(out, f));
  }
  return { landing, bytes: page.length };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({ options: { target: { type: 'string', default: 'prod' }, out: { type: 'string', default: path.join(here, 'dist') } } });
  const res = await build({ target: values.target, out: path.resolve(values.out) });
  console.log(`landing (${values.target}): wrote ${res.landing} (index.html ${res.bytes} bytes)`);
}
